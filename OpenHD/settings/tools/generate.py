#!/usr/bin/env python3
"""Validate the authoring catalog and generate reproducible consumer artifacts."""
import argparse
import json
import pathlib
import re
import hashlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
def identifier(name):
    result=name.replace('.', '_DOT_').replace('-', '_DASH_')
    return 'P_'+result if result[0].isdigit() else result

def validate(doc):
    if doc.get('version') != 1 or not isinstance(doc.get('settings'), list):
        raise ValueError('Unsupported settings catalog')
    seen = set()
    identifiers=set()
    for entry in doc['settings']:
        name = entry['id']
        if not re.fullmatch(r'[A-Za-z0-9_.-]{1,16}', name) or name in seen:
            raise ValueError(f'Invalid or duplicate MAVLink ID: {name}')
        seen.add(name)
        symbol=identifier(name)
        if symbol in identifiers: raise ValueError(f'Generated C++ ID collision: {name}')
        identifiers.add(symbol)
        for field in ('label','description','group'):
            if field in entry and not isinstance(entry[field],str): raise ValueError(f'Invalid {field}: {name}')
        for field in ('readOnly','requiresReboot','hidden','enforce'):
            if field in entry and type(entry[field]) is not bool: raise ValueError(f'Invalid {field}: {name}')
        for field in ('minimum','maximum'):
            if field in entry and (type(entry[field]) is not int or not -2147483648<=entry[field]<=2147483647):
                raise ValueError(f'Invalid int32 {field}: {name}')
        if entry['type'] not in ('int32', 'string', 'runtime'):
            raise ValueError(f'Invalid type: {name}')
        values = [c['value'] for c in entry.get('choices', [])]
        if len({json.dumps(v) for v in values}) != len(values):
            raise ValueError(f'Duplicate choice: {name}')
        if entry['type'] == 'int32' and any(type(v) is not int for v in values):
            raise ValueError(f'Non-integer choice: {name}')
        if entry['type'] == 'string' and any(not isinstance(v, str) or len(v.encode()) > 128 for v in values):
            raise ValueError(f'Invalid string choice: {name}')
        if entry.get('minimum', -2147483648) > entry.get('maximum', 2147483647):
            raise ValueError(f'Inverted range: {name}')

def outputs(doc):
    platforms=json.loads((ROOT/'platforms.json').read_text())
    boards=platforms['platforms']
    if platforms['version']!=1 or len({p['id'] for p in boards})!=len(boards):
        raise ValueError('Platform choices require unique board IDs')
    for p in boards:
        if not re.fullmatch(r'[a-z0-9-]{1,40}',p['id']) or not p['label'] or type(p['platformId']) is not int or not p['sbc']:
            raise ValueError('Invalid platform definition')
    # SysUtils is a separate checkout; audit full coverage when it is available.
    owner=ROOT.parents[1]/'OpenHD-SysUtils/misc/platforms.json'
    if owner.exists():
        known=json.loads(owner.read_text())['platforms']
        if {p['platformId'] for p in boards}!={p['id'] for p in known if p['id']!=0}:
            raise ValueError('Platform choices must cover every known SysUtils platform')
    runtime={'version':doc['version'],'settings':doc['settings']}
    encoded = json.dumps(runtime, ensure_ascii=True, separators=(',', ':'))
    header = '// Generated by settings/tools/generate.py; edit settings/catalog.json.\n#pragma once\n'
    header += 'namespace openhd::settings {\ninline constexpr const char catalog_json[] = R"ohdcatalog(' + encoded + ')ohdcatalog";\n'
    header += 'namespace ids {\n'
    for entry in doc['settings']:
        ident = identifier(entry['id'])
        header += f'inline constexpr const char {ident}[] = "{entry["id"]}";\n'
    header += '}\n}\n'
    imagewriter=dict(doc['imageWriter'])
    imagewriter['platforms']=boards
    imagewriter['_settingsContract']={'version':1,'catalogHash':hashlib.sha256(encoded.encode()).hexdigest()}
    imagewriter['initialFields']=[entry for entry in doc['settings'] if entry.get('provision')]
    cameras=json.loads((ROOT.parent/'ohd_video/misc/camera_registry.json').read_text())['camera_types']
    camera_types=[{'value':entry['id'],'label':entry.get('ui_label',entry['name'])} for entry in cameras]
    camera_types.append({'value':255,'label':'Disabled'})
    webui='// Generated from OpenHD/settings; do not edit.\n'
    webui+='export const CAMERA_TYPES = '+json.dumps(camera_types,ensure_ascii=True)+';\n'
    webui+='export const LEGACY_SETTINGS_METADATA = '+json.dumps(doc.get('legacyWebUi',{}),ensure_ascii=True)+';\n'
    return {ROOT / 'generated/catalog.h': header,
            ROOT / 'generated/platforms.json': json.dumps(platforms,indent=2)+'\n',
            ROOT / 'generated/platforms.ts': '// Generated from OpenHD/settings/platforms.json; do not edit.\nexport const PLATFORMS = '+json.dumps(boards,ensure_ascii=True)+' as const;\n',
            ROOT / 'generated/catalog.json': json.dumps(runtime, indent=2, ensure_ascii=False) + '\n',
            ROOT / 'generated/imagewriter-settings.json': json.dumps(imagewriter, indent=2, ensure_ascii=False) + '\n',
            ROOT / 'generated/webui-metadata.ts':webui}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    doc = json.loads((ROOT / 'catalog.json').read_text(encoding='utf-8-sig'))
    validate(doc)
    for path, content in outputs(doc).items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Out of date: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    print(f'Validated {len(doc["settings"])} setting definitions')

if __name__ == '__main__':
    main()
